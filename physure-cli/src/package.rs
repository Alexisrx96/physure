    #[test]
    fn test_manifest_validation_and_packing_lifecycle() {
        let temp_dir = std::env::temp_dir().join(format!("phs_pack_test_{}", Utc::now().timestamp_nanos_opt().unwrap_or(0)));
        fs::create_dir_all(temp_dir.join("models")).unwrap();

        let manifest_content = r#"
[package]
name = "demo-pack"
version = "0.1.0"
entry = "main.phs"

[exports]
kinetics = "models/kinetics.phs"
geometry = "models/geometry.phs"
"#;
        fs::write(temp_dir.join("phs.toml"), manifest_content).unwrap();
        fs::write(
            temp_dir.join("main.phs"),
            "fn main() = 42
",
        ).unwrap();
        fs::write(
            temp_dir.join("models/kinetics.phs"),
            "/// Kinetic energy calculation
/// @param m Mass in kg
/// @param v Speed in m/s
fn E_k(m: kg, v: m/s) = 0.5 * m * v^2
",
        ).unwrap();
        fs::write(
            temp_dir.join("models/geometry.phs"),
            "fn circle_area(r: m) = 3.1415926535 * r^2
fn rectangle_area(w: m, h: m) = w * h
",
        ).unwrap();

        let manifest = Manifest::from_file(temp_dir.join("phs.toml")).unwrap();
        let report = manifest.validate(&temp_dir).unwrap();

        assert_eq!(report.package_name, "demo-pack");
        assert_eq!(report.version, "0.1.0");
        assert_eq!(report.modules.len(), 2);
        assert_eq!(report.total_functions, 3);

        // Pack the package
        let bundle_file = temp_dir.join("dist/demo-pack-0.1.0.phspkg");
        let (packed_path, pack_report) = manifest.pack(&temp_dir, Some(&bundle_file)).unwrap();
        assert_eq!(packed_path, bundle_file);
        assert_eq!(pack_report.total_functions, 3);
        assert!(bundle_file.is_file());

        // Load the bundle back
        let bundle = PhsPackageBundle::from_file(&bundle_file).unwrap();
        assert_eq!(bundle.format_version, 1);
        assert_eq!(bundle.manifest.package.name, "demo-pack");
        assert_eq!(bundle.modules.len(), 2);

        let kinetics = &bundle.modules["kinetics"];
        assert_eq!(kinetics.export_name, "kinetics");
        assert!(kinetics.functions.contains_key("E_k"));
        let e_k = &kinetics.functions["E_k"];
        assert_eq!(e_k.params.len(), 2);
        assert_eq!(e_k.params[0].name, "m");
        assert_eq!(e_k.params[0].expected_unit.as_deref(), Some("kg"));

        let _ = fs::remove_dir_all(&temp_dir);
    }

