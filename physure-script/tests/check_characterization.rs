//! Characterization of the static checker (sonar S3776 cleanup): every finding, in order, with its line, severity,
//! code and exact message, for programs that reach each branch of the reserved-name pass, of conversions and
//! operations, and of the builtins the checker knows, as the checker reported them before those functions were split
//! into helpers. `check.rs` says what the findings should be; this table pins that a refactor changes none of them.

use physure_script::check::check_source;

/// Every finding of `source`, one per line, or the parse error.
fn findings(source: &str) -> String {
    match check_source(source) {
        Ok(diagnostics) => diagnostics
            .iter()
            .map(|d| format!("{}:{:?}:{}:{}", d.line, d.severity, d.code, d.message))
            .collect::<Vec<_>>()
            .join("\n"),
        Err(error) => format!("parse error {error}"),
    }
}

